/* =====================================================================
   typo() — экранная типографика, как в хорошем журнале. Работает при СБОРКЕ сайта,
   посетитель получает уже готовый текст (никакого JS в браузере).

   Что делает:
   1. Неразрывный пробел после коротких предлогов и союзов («в Кишинёве», «и CRM», «de la»,
      «of the»): короткое слово не остаётся «висеть» в конце строки.
   2. Неразрывный пробел перед длинным тире: тире не переносится в начало новой строки.
   3. Цены и числа: «от €250», «€1 500», «30 минут», «98 водителей», «1–2 недели», «17 mi»
      — число не отрывается от валюты, единицы и слова «от».
   Кавычки в текстах уже правильные для каждого языка: «ёлочки» — ru, „…” — ro (так принято
   в румынской типографике), “…” — en. Их функция не меняет.

   Текст может содержать HTML (<em>, <b>, <a href="…">): функция меняет только текст
   между тегами, атрибуты и сами теги не трогает.
   ===================================================================== */
import type { Lang } from './index';

const NBSP = ' ';

// Короткие слова, после которых ставим неразрывный пробел (сравнение без учёта регистра)
const SHORT: Record<Lang, string[]> = {
  ru: ['в', 'во', 'к', 'ко', 'с', 'со', 'у', 'о', 'об', 'и', 'а', 'но', 'на', 'по', 'за', 'от', 'до', 'из',
       'не', 'ни', 'для', 'без', 'при', 'под', 'над', 'про', 'что', 'как', 'или', 'же', 'ли', 'мы', 'вы'],
  ro: ['o', 'a', 'în', 'la', 'de', 'cu', 'pe', 'și', 'nu', 'un', 'o', 'al', 'ale', 'ca', 'să', 'din', 'pentru',
       'sau', 'dar', 'fără', 'prin', 'spre', 'vă', 'le', 'ne', 'se', 'e'],
  en: ['a', 'an', 'the', 'of', 'to', 'in', 'on', 'at', 'by', 'for', 'and', 'or', 'no', 'is', 'it', 'as',
       'we', 'i', 'up', 'from', 'with', 'your', 'our', 'per'],
};

// Единицы и слова, которые не отрываем от числа перед ними
const UNITS = ['мин', 'минут', 'минуты', 'сек', 'дн', 'дней', 'дня', 'недели', 'недель', 'часов', 'млн', 'тыс',
  'mi', 'min', 'minute', 'minutes', 'sec', 'zi', 'zile', 'săptămâni', 'mil', 'mln', 'days', 'day', 'weeks', 'hours',
  '%', '€', '$', 'API', 'постов', 'posturi', 'bays', 'водителей', 'диспетчеров', 'шага', 'steps', 'pași',
  'строки', 'таблиц', 'экранов', 'адресов', 'языка', 'марка', 'лотов', 'клик', 'click', 'clic', 'lei'];

const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

function fixText(s: string, lang: Lang): string {
  // 1) Короткие слова: «в Кишинёве» → «в Кишинёве». Повторяем дважды для цепочек («и в 1С»).
  const words = SHORT[lang].map(esc).join('|');
  const short = new RegExp(`(^|[\\s(«„“${NBSP}])(${words}) `, 'giu');
  s = s.replace(short, `$1$2${NBSP}`).replace(short, `$1$2${NBSP}`);
  // 2) Тире: пробел перед « — » становится неразрывным
  s = s.replace(/ (—|–) /g, `${NBSP}$1 `);
  // 3) Цены: «от €250», «de la €600», «from €800»
  s = s.replace(/(^|\s)(от|de la|from|до|up to|până la) (€|\$)/giu, `$1$2${NBSP}$3`);
  //    тысячи через пробел: «€1 500», «$ 2 450», «1 214 mi» — пробел внутри числа неразрывный
  s = s.replace(/(\d) (\d{3})(?!\d)/g, `$1${NBSP}$2`);
  //    «$ 2 450» — знак валюты не отрываем от числа
  s = s.replace(/([€$]) (\d)/g, `$1${NBSP}$2`);
  // 4) Число + единица: «30 минут», «17 mi», «98 водителей»
  const units = UNITS.map(esc).join('|');
  s = s.replace(new RegExp(`(\\d) (${units})(?![\\p{L}])`, 'gu'), `$1${NBSP}$2`);
  return s;
}

/** Типографика строки с возможным HTML внутри. */
export function typo(html: string, lang: Lang): string {
  if (!html) return html;
  // Делим строку на теги и текст: теги (<…>) пропускаем как есть, текст обрабатываем
  return html
    .split(/(<[^>]+>)/g)
    .map((part) => (part.startsWith('<') ? part : fixText(part, lang)))
    .join('');
}

/** Висячая пунктуация: если заголовок начинается с кавычки, выносим её за левый край
 *  (оптически ровный край текста, как в журналах). Класс .hang — в global.css */
export function hang(html: string): string {
  return html.replace(/^([«„“])/, '<span class="hang">$1</span>');
}
