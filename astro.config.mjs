// =====================================================================
// Настройки Astro — генератора статического сайта.
// Astro собирает из компонентов (src/components) и текстов (src/i18n) обычные HTML-страницы
// в папку dist/. На хостинг уходит только dist/ — там нет ни Node.js, ни сервера, только файлы.
// =====================================================================
import { defineConfig } from 'astro/config';

export default defineConfig({
  // Основной адрес сайта: из него строятся canonical, hreflang, og:url и карта сайта
  site: 'https://mxsystems.md',

  // Полностью статическая сборка: каждая страница — готовый HTML-файл
  output: 'static',

  // Все адреса со слэшем на конце (/ro/, /privacy/) — ровно как в старой версии сайта.
  // Тогда ссылки, canonical и адреса в Google не меняются при переезде на Astro.
  trailingSlash: 'always',

  build: {
    // /ro/ → dist/ro/index.html (папка + index.html), а не dist/ro.html
    format: 'directory',
    // Строгая CSP запрещает встроенные <style>. 'never' — все стили выносятся в отдельные .css-файлы
    inlineStylesheets: 'never',
    // Папка для собранных CSS/JS/шрифтов/картинок с хешем в имени (кэшируются навсегда)
    assets: '_astro',
  },

  vite: {
    build: {
      // 0 — никогда не вставлять мелкие файлы (скрипты, шрифты, картинки) прямо в HTML/CSS как data:
      // Иначе Vite «встроил» бы маленький скрипт в страницу, и CSP его заблокировала бы
      assetsInlineLimit: 0,
    },
  },

  // Панель разработчика Astro в режиме dev не нужна (она добавляет свои скрипты)
  devToolbar: { enabled: false },
});
